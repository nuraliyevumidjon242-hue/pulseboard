/**
 * Builds the German and Uzbek dictionaries.
 *
 * English source strings are the keys. A curated set of high-visibility copy
 * is written by hand for tone and terminology, and everything else is machine
 * translated in batches. Placeholders such as {{count}} are masked before the
 * request and restored afterwards so interpolation keeps working.
 *
 * Usage: node scripts/generate-translations.cjs
 */
const fs = require('fs');
const path = require('path');

const keysPath = path.join(process.cwd(), 'apps/web/src/lib/translations/keys.json');
const curatedPath = path.join(__dirname, 'i18n-curated.cjs');
const correctionsPath = path.join(__dirname, 'i18n-corrections.cjs');
const outDir = path.join(process.cwd(), 'apps/web/src/lib/translations');

const keys = JSON.parse(fs.readFileSync(keysPath, 'utf8'));
const curated = fs.existsSync(curatedPath) ? require(curatedPath) : { de: {}, uz: {} };
const corrections = fs.existsSync(correctionsPath) ? require(correctionsPath) : { de: {}, uz: {} };
for (const target of ['de', 'uz']) {
  curated[target] = { ...(curated[target] ?? {}), ...(corrections[target] ?? {}) };
}

function mask(value) {
  return value.replace(/\{\{(\w+)\}\}/g, (_, name) => `__PH_${name.toUpperCase()}__`);
}

function unmask(value) {
  return value.replace(/__PH_([A-Z0-9_]+?)__/g, (_, name) => `{{${name.toLowerCase()}}}`);
}

async function translateBatch(lines, target) {
  const query = lines.map(mask).join('\n');
  const url =
    'https://translate.googleapis.com/translate_a/single?client=gtx&sl=en&tl=' +
    target +
    '&dt=t&q=' +
    encodeURIComponent(query);

  for (let attempt = 0; attempt < 4; attempt += 1) {
    try {
      const response = await fetch(url);
      if (!response.ok) throw new Error(`HTTP ${response.status}`);
      const payload = await response.json();
      const text = payload[0].map((chunk) => chunk[0]).join('');
      const translated = text.split('\n');
      if (translated.length !== lines.length) {
        throw new Error(`line mismatch ${translated.length} != ${lines.length}`);
      }
      return translated.map(unmask);
    } catch (error) {
      if (attempt === 3) throw error;
      await new Promise((resolve) => setTimeout(resolve, 500 * (attempt + 1)));
    }
  }
  return lines;
}

async function build(target) {
  const overrides = curated[target] ?? {};
  const missing = keys.filter((key) => !overrides[key]);

  // Keep each request well under the endpoint's URL length limits.
  const batches = [];
  let batch = [];
  let size = 0;
  for (const key of missing) {
    const cost = encodeURIComponent(mask(key)).length + 3;
    if (batch.length > 0 && size + cost > 4000) {
      batches.push(batch);
      batch = [];
      size = 0;
    }
    batch.push(key);
    size += cost;
  }
  if (batch.length > 0) batches.push(batch);

  const result = {};
  for (const key of keys) if (overrides[key]) result[key] = overrides[key];

  for (let index = 0; index < batches.length; index += 1) {
    const group = batches[index];
    const translated = await translateBatch(group, target);
    group.forEach((key, position) => {
      result[key] = translated[position];
    });
    process.stdout.write(`\r${target}: ${index + 1}/${batches.length} batches`);
  }
  process.stdout.write('\n');

  return result;
}

function serialize(target, dictionary) {
  const lines = Object.keys(dictionary)
    .sort((a, b) => a.localeCompare(b))
    .map((key) => `  ${JSON.stringify(key)}: ${JSON.stringify(dictionary[key])},`);

  return `// Generated by scripts/generate-translations.cjs. Keys are English source
// strings, so a missing entry still renders readable English. Curated copy lives
// in scripts/i18n-curated.cjs; run the script after adding keys.
export const ${target}: Record<string, string> = {
${lines.join('\n')}
};
`;
}

(async () => {
  for (const target of ['de', 'uz']) {
    const dictionary = await build(target);
    fs.writeFileSync(path.join(outDir, `${target}.ts`), serialize(target, dictionary), 'utf8');
    console.log(`${target}: ${Object.keys(dictionary).length} entries`);
  }
})();
